export function localizeTemplatePhrase(text, locale = "it"){
  const raw = String(text || "");
  if(!raw || locale !== "en") return raw;
  return TEMPLATE_PHRASE_EN[raw] || raw;
}

export function localizeMomentTemplate(template, locale = "it"){
  if(!template || locale !== "en") return template;
  const walk = (value)=>{
    if(typeof value === "string") return localizeTemplatePhrase(value, locale);
    if(Array.isArray(value)) return value.map(walk);
    if(value && typeof value === "object"){
      const out = {};
      for(const [k, v] of Object.entries(value)) out[k] = walk(v);
      return out;
    }
    return value;
  };
  return walk(template);
}

